package com.qian.qianaiagent.ability;

/**
 * 🔴 [终版-双链路] 维度分类置信度等级
 *
 * <p>由双链路互证门自动划分，不实时修正，仅标记等级随数据落库。</p>
 */
public enum ConfidenceLevel {

    /** 链路A和链路B一致，且评分 AI 自评高置信。最高信用等级，直接入正式统计库。 */
    HIGH,

    /** 自由出题场景，仅依赖链路B（评分 AI 标注），无链路A交叉验证。正常入库但标记。 */
    MEDIUM,

    /** 仅有单链路的有效维度，或评分 AI 自评为 low/medium 置信。可入库但标记为待关注。 */
    LOW,

    /** 链路A和链路B输出的维度完全不一致，无法合并。打入离线异常队列。 */
    CONFLICT,

    /** 维度名验证失败（幻觉维度名/不存在于白名单）。打入离线异常队列。 */
    INVALID,

    /** 降级层生成（LLM 熔断时主体名匹配）。强制标记降级，服务恢复后自动重分类。 */
    FALLBACK
}
